"""v40 (APK v36.7) player energy redesign: charge = sparse individual electrical discharges, no continuous loop.

Sources: ElevenLabs components e40_* (tools/audio/elevenlabs_sources.json, generated by
generate_elevenlabs_sources.py) in Assets/Characters/Players/NewAudioMasters/candidates/. Kept generations are
copied unprocessed to NewAudioMasters/<component>_<n>.wav; rejected ones go to candidates/rejected/.
Processing: trim, 4th-order low-pass (electric crackle is naturally bright; keeps energy above 6 kHz low), +-3 %
pitch variants, per-family loudness. Families (game/assets/audio/v40/, merged as "v40/..." into bank.json):
  v40/charge_micro     tiny ticks (incl. first transients cut from crackle/snap takes)    20-50 % charge
  v40/charge_crackle   small arc crackles                                               ~50-75 %
  v40/charge_snap      stronger capacitor snaps                                         ~75-95 %
  v40/charge_nearfull  short bursts of snaps                                             ~95-99.9 %
  v40/energy_full      one completion event (snap cluster + settling discharge)          100 %, once per fill
  v40/energy_release   charged-landing release: deep electric thump + dry arc crack, tiered by stored charge
Objective checks only - nobody listened. usage: python -B -I tools/audio/build_energy_v40.py
"""
from pathlib import Path
import json, math, shutil, sys
import numpy as np
from scipy.io import wavfile
from scipy.signal import butter, sosfilt

sys.path.insert(0, str(Path(__file__).parent))
import build_v39_sound_design as v39  # noqa  (read / trim / pitch / mix / level / write helpers)
from audio_metrics import loudness  # noqa

ROOT = v39.ROOT
CAND = v39.CAND
KEEP = v39.KEEP
OUT = v39.OUT
RUN = OUT / "v40"
SR = v39.SR
# objective rejections (see analysis.json): too bright (> 6 kHz share) or not a spark at all
REJECT = {"e40_micro__c1": "near silent + 75 % above 6 kHz", "e40_micro__c3": "centroid 34 Hz - rumble, not a spark",
          "e40_crackle__c2": "69 % above 6 kHz", "e40_nearfull__c1": "83 % above 6 kHz",
          "e40_snap__c4": "64 % above 6 kHz", "e40_full__c4": "64 % above 6 kHz"}


def lp4(x, f=6000): return sosfilt(butter(4, f, "low", fs=SR, output="sos"), x)


def load(stem, f=6000):
    return v39.trim(lp4(v39.read(CAND / f"{stem}.wav"), f))


def kept(comp):
    return sorted(p.stem for p in CAND.glob(f"{comp}__c*.wav") if p.stem not in REJECT)


def first_transient(x, dur=.07):
    y = v39.trim(x, dur, fade=.03)
    return y


def write(name, y):
    p = RUN / f"{name}.wav"
    p.parent.mkdir(parents=True, exist_ok=True)
    wavfile.write(p, SR, (np.clip(y, -1, 1) * 32767).astype(np.int16))
    imp = Path(str(p) + ".import")
    if not imp.exists():
        imp.write_text('[remap]\n\nimporter="wav"\ntype="AudioStreamWAV"\n\n[params]\n\nforce/8_bit=false\nforce/mono=false\n'
                       'force/max_rate=false\nforce/max_rate_hz=44100\nedit/trim=false\nedit/normalize=false\nedit/loop_mode=0\n'
                       'edit/loop_begin=0\nedit/loop_end=-1\ncompress/mode=2\n', encoding="utf-8")
    return p


FAMS, REPORT = {}, {}


def family(fam, clips, target):
    order = sorted(range(len(clips)), key=lambda j: loudness(clips[j][:, None], SR))
    entries = []
    for rank, j in enumerate(order):
        y = v39.level(clips[j], target)
        p = write(f"{fam}_{rank + 1:02d}", y)
        S = np.abs(np.fft.rfft(y)) ** 2; f = np.fft.rfftfreq(len(y), 1 / SR)
        entries.append({"path": f"res://assets/audio/v40/{p.name}", "energy": round(float(np.sqrt(np.mean(y ** 2))), 4),
                        "duration": round(len(y) / SR, 3), "loop": False, "tier": round(rank / max(1, len(clips) - 1), 4),
                        "hf6k": round(float(S[f > 6000].sum() / S.sum()), 3)})
    FAMS[f"v40/{fam}"] = entries
    REPORT[fam] = {"n": len(entries), "max_hf6k": max(e["hf6k"] for e in entries), "max_dur": max(e["duration"] for e in entries)}


def main():
    rej = CAND / "rejected"; rej.mkdir(exist_ok=True)
    for stem in REJECT:
        if (CAND / f"{stem}.wav").exists():
            shutil.move(str(CAND / f"{stem}.wav"), str(rej / f"{stem}.wav"))
    comps = {c: kept(c) for c in ("e40_micro", "e40_crackle", "e40_snap", "e40_nearfull", "e40_full", "e40_release")}
    for c, stems in comps.items():
        for n, s in enumerate(stems, 1):
            shutil.copyfile(CAND / f"{s}.wav", KEEP / f"{c}_{n}.wav")
    before = set(RUN.glob("*.wav")) if RUN.exists() else set()
    cr = [load(s) for s in comps["e40_crackle"]]
    sn = [v39.trim(load(s), .35, fade=.06) for s in comps["e40_snap"]]
    micro = [v39.trim(load(s, 5500), .18, fade=.05) for s in comps["e40_micro"]] + [first_transient(x) for x in cr] + [first_transient(x, .06) for x in sn[:2]]
    family("charge_micro", [v39.pitch(x, pr) for x in micro for pr in (.98, 1.02)], -31.0)
    family("charge_crackle", [v39.pitch(x, pr) for x in cr for pr in (.97, 1.03)], -26.0)
    family("charge_snap", [v39.pitch(x, pr) for x in sn for pr in (.97, 1.03)], -23.0)
    nf = [load(s) for s in comps["e40_nearfull"]]
    family("charge_nearfull", [v39.pitch(x, pr) for x in nf for pr in (.98, 1.02)], -21.0)
    family("energy_full", [v39.trim(load(s), .7, fade=.08) for s in comps["e40_full"]], -17.0)
    rel = [load(s, 9000) for s in comps["e40_release"]]
    family("energy_release", [v39.pitch(v39.mix((r, 0), (sn[k % len(sn)] * v39.db(-5), .006)), pr)
                              for k, r in enumerate(rel) for pr in (.98, 1.02)], -15.0)
    for p in before - {RUN / Path(e["path"]).name for v in FAMS.values() for e in v}:
        p.unlink(); Path(str(p) + ".import").unlink(missing_ok=True)
    bank_path = OUT / "bank.json"
    bank = json.loads(bank_path.read_text(encoding="utf-8"))
    bank["banks"] = {k: v for k, v in bank["banks"].items() if not k.startswith("v40/")}
    bank["banks"].update(FAMS)
    bank_path.write_text(json.dumps(bank, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    (ROOT / "reports/v40_audio").mkdir(parents=True, exist_ok=True)
    (ROOT / "reports/v40_audio/build.json").write_text(json.dumps({"kept": comps, "rejected": REJECT, "families": REPORT}, indent=1), encoding="utf-8")
    for k, v in REPORT.items():
        print(f"{k:16s} {v}")


if __name__ == "__main__":
    main()

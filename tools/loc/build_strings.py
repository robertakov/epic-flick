"""v34 localization build: tools/loc/parts/*.json -> game/locale/strings.json.

Parts are column tables: "KEY": [ru, en, es, pt_BR, fr, de, it, pl, tr, uk, zh_CN, ja, ko].
"KEY@p" = plural phrase; each cell holds the locale's forms joined by "|" in category order
(ru/uk/pl one|few|many, zh_CN/ja/ko other, everything else one|other) -> KEY_one / KEY_few / ...
"D_*" keys also go into the data map (exact Russian data text -> key) used by L.data().

Checks (build fails on any): duplicate keys, wrong column count, empty cells, wrong plural form count,
placeholder mismatch against the Russian source (%d / %s / %% counts and {named} sets).
Run:  python tools/loc/build_strings.py
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PARTS = os.path.join(ROOT, "tools", "loc", "parts")
OUT = os.path.join(ROOT, "game", "locale", "strings.json")
COLS = ["ru", "en", "es", "pt_BR", "fr", "de", "it", "pl", "tr", "uk", "zh_CN", "ja", "ko"]
CATS = {"ru": ["one", "few", "many"], "uk": ["one", "few", "many"], "pl": ["one", "few", "many"],
        "zh_CN": ["other"], "ja": ["other"], "ko": ["other"]}


def cats(loc):
    return CATS.get(loc, ["one", "other"])


def sig(s):
    s2 = s.replace("%%", "")
    return (sorted(re.findall(r"%[ds]", s2)), sorted(set(re.findall(r"\{(\w+)\}", s))))


def main():
    strings, data, errors = {}, {}, []
    for fn in sorted(os.listdir(PARTS)):
        if not fn.endswith(".json"):
            continue
        src = json.load(open(os.path.join(PARTS, fn), encoding="utf-8"))
        if src.get("_columns") != COLS:
            errors.append(f"{fn}: _columns mismatch")
        for key, row in src.items():
            if key.startswith("_"):
                continue
            plural = key.endswith("@p")
            base = key[:-2] if plural else key
            if not re.fullmatch(r"[A-Z][A-Z0-9_]*", base):
                errors.append(f"{fn}:{key}: bad key name")
            if not isinstance(row, list) or len(row) != len(COLS):
                errors.append(f"{fn}:{key}: needs {len(COLS)} columns")
                continue
            ru_sig = None
            for loc, cell in zip(COLS, row):
                if not isinstance(cell, str) or cell.strip() == "":
                    errors.append(f"{fn}:{key}:{loc}: empty")
                    continue
                forms = cell.split("|") if plural else [cell]
                if plural and len(forms) != len(cats(loc)):
                    errors.append(f"{fn}:{key}:{loc}: {len(forms)} plural forms, expected {len(cats(loc))} {cats(loc)}")
                    continue
                for i, form in enumerate(forms):
                    k = f"{base}_{cats(loc)[i]}" if plural else base
                    if loc == "ru" and k in strings:
                        errors.append(f"{fn}:{k}: duplicate key")
                    strings.setdefault(k, {})[loc] = form
                    s = sig(form)
                    if ru_sig is None:
                        ru_sig = s
                    elif s != ru_sig:
                        errors.append(f"{fn}:{key}:{loc}: placeholders {s} != ru {ru_sig}")
            if base.startswith("D_"):
                if row[0] in data:
                    errors.append(f"{fn}:{key}: data text duplicated with {data[row[0]]}")
                data[row[0]] = base
    if errors:
        print("\n".join(errors))
        print(f"FAILED: {len(errors)} problems")
        sys.exit(1)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    out = {"_comment": "GENERATED by tools/loc/build_strings.py from tools/loc/parts - edit the parts, not this file.",
           "locales": COLS, "plural_categories": {l: cats(l) for l in COLS}, "strings": strings, "data": data}
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        json.dump(out, f, ensure_ascii=False, indent=1, sort_keys=False)
    print(f"OK: {len(strings)} keys, {len(data)} data names -> {OUT}")


if __name__ == "__main__":
    main()
